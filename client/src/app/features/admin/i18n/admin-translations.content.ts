function withOverrides(
  base: Record<string, string>,
  overrides: Record<string, string>,
): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of Object.keys(base)) {
    out[key] = overrides[key] ?? base[key];
  }
  return out;
}

