# Remove ALL node_modules from Git tracking (keeps folders on disk)
# Run from repo root: .\remove-node_modules-from-git.ps1

Write-Host "Finding all tracked node_modules..." -ForegroundColor Yellow

# Get all tracked files under any node_modules
$tracked = git ls-files "**/node_modules/**" 2>$null
if (-not $tracked) {
    Write-Host "No node_modules are tracked by Git. Repository is clean." -ForegroundColor Green
    exit 0
}

# Get unique top-level node_modules paths (e.g. server/node_modules, client/ali/node_modules, or node_modules at root)
$roots = @{}
foreach ($file in $tracked) {
    if ($file -match '^(.+?/node_modules)/') {
        $roots[$Matches[1]] = $true
    } elseif ($file -match '^node_modules/') {
        $roots['node_modules'] = $true
    }
}

if ($roots.Count -eq 0) {
    Write-Host "No node_modules are tracked by Git." -ForegroundColor Green
    exit 0
}

Write-Host "Removing from Git index:" -ForegroundColor Yellow
foreach ($path in $roots.Keys | Sort-Object) {
    git rm -r --cached $path 2>$null
    if ($LASTEXITCODE -eq 0) {
        Write-Host "  $path" -ForegroundColor Green
    }
}

Write-Host "`nDone. Next steps:" -ForegroundColor Cyan
Write-Host "  git add .gitignore"
Write-Host "  git add server/.gitignore"
Write-Host "  git add client/.gitignore"
Write-Host "  git commit -m `"Remove all node_modules from repository`""
Write-Host "  git push"
