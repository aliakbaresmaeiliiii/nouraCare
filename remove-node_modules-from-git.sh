#!/bin/sh
# Remove ALL node_modules from Git tracking (keeps folders on disk)
# Run from repo root: sh remove-node_modules-from-git.sh

echo "Finding all tracked node_modules..."

# Remove every tracked path under any node_modules
git ls-files '**/node_modules/**' | while read -r f; do
  git rm --cached "$f" 2>/dev/null
done

# Also remove top-level node_modules dirs if tracked
for dir in server/node_modules client/node_modules client/ali/node_modules client/android/node_modules client/android/app/node_modules node_modules; do
  if [ -d "$dir" ]; then
    git rm -r --cached "$dir" 2>/dev/null && echo "  Removed $dir"
  fi
done

echo ""
echo "Done. Next steps:"
echo "  git add .gitignore server/.gitignore client/.gitignore"
echo "  git commit -m \"Remove all node_modules from repository\""
echo "  git push"
